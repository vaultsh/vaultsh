def set_language(language: str) -> None:
    """Set interface language; unsupported values fail rather than silently guessing."""
    global _CURRENT_LANGUAGE
    normalized = language.strip().lower()
    if normalized not in LANGUAGES:
        choices = ", ".join(LANGUAGES)
        raise ValueError(f"Unsupported language {language!r}; choose one of: {choices}")
    _CURRENT_LANGUAGE = normalized


def get_language() -> str:
    """Return the current language code."""
    return _CURRENT_LANGUAGE


def tr(key: str) -> str:
    """Translate a UI string, falling back to English for missing keys."""
    return _TRANSLATIONS.get(_CURRENT_LANGUAGE, _TRANSLATIONS["en"]).get(
        key, _TRANSLATIONS["en"].get(key, key)
    )
